#pragma once

// Reading DTA text into trees.
//
//   baker::Ref<baker::Array> menu = baker::read_file("menu.dta");
//
// The parser is also the preprocessor. Directives are handled while reading and never
// appear in the tree:
//
//   #include path        splice another file's top-level nodes here
//   #include_opt path    the same, but a missing file is not an error
//   #include_dir path    a child for each .dta file of a directory, named by the file and
//                        holding its nodes, and for each subdirectory, named by it and
//                        holding its own; in the order its order.dta lists, then by name
//   #require path        the same, once per session: later #requires of that file, from
//                        any file the session reads, are no-ops (for packs)
//   #merge path          merge another file into the enclosing array, keeping existing
//                        keys and adding missing ones
//   #ifdef N / #ifndef N / #else / #endif
//   #define N            define N (for #ifdef)
//   #define N (body)     define N as a macro whose body is the array's contents (the
//                        array must start on the same line)
//   #undef N
//   #autorun {command}   collect the command into LoadSession::autorun
//   [N node ...]         at the top level of a file: define macro N
//
// Packs. A file whose first form is
//   (pack name (level L) (requires other ...)
//         (owners "td-encounter" "td-combat") (for designers) (stage custom))
// is a pack at level L of the session's pack levels (set_pack_levels, hardest first); the
// form is recorded and left out of the tree. owners, for, and stage are optional harness
// metadata (the stage is genesis, custom, product, or commodity). Expanding a macro that a
// softer pack defined, in a harder pack's file, is a warning (the one-way rule): it is kept
// in warnings(), with file and line. Files that declare no pack are unconstrained.
//
// Origins. A file whose first form (or the first after its pack
// declaration) is
//   (origin "economy.xlsx" (tool sheets-export))
// was generated by an external tool; the form is recorded and left out of the tree, and
// Config::source() names the origin and tool of every value the file supplies. The
// origin's first value must be a string, so ordinary data such as (origin 0 0 0) is not
// taken for one.
//
// A macro name written as a bare symbol is replaced by the macro's nodes. Expansion
// shares arrays instead of copying them. Paths may be "quoted" or bare.
//
// Nothing in a file can crash the reader: malformed input yields a located Error, and
// ParseLimits bounds nesting, includes, and total size.

#include <baker/array.hpp>
#include <baker/error.hpp>
#include <baker/source_map.hpp>

#include <baker/callback.hpp>
#include <baker/list.hpp>
#include <baker/text.hpp>

#include <cstdint>
#include <initializer_list>
#include <span>
#include <string_view>

namespace baker {

struct Cipher;  // cache.hpp
namespace detail {
class Parser;
struct SessionAccess;  // the binary cache's view of a session
}  // namespace detail

struct ParseLimits {
    uint32_t max_depth = 256;                // array nesting, including spliced macro arrays
    uint32_t max_include_depth = 32;         // #include / #merge nesting
    uint32_t max_includes = 4096;            // files opened per top-level read
    uint64_t max_nodes = uint64_t{1} << 26;  // nodes created per top-level read
};

// A file that declared itself a pack (above).
struct Pack {
    Symbol name;
    Symbol level;
    uint32_t rank = 0;  // the level's place in the session's pack levels; 0 is the hardest
    Symbol file;
    List<Symbol> requires_packs;
    // The version each required pack must be at least, parallel to requires_packs: empty for
    // any. From (requires (base "1.2") other).
    List<Symbol> requires_versions;
    // (version "1.2"): dot-separated integers, compared part by part; empty when undeclared.
    Symbol version;
    // Harness metadata: who keeps the pack, whom it is for, and how far it has
    // evolved. Empty when not declared.
    List<Symbol> owners;    // (owners "td-encounter" "td-combat")
    List<Symbol> audience;  // (for designers)
    Symbol stage;           // genesis, custom, product, or commodity
};

// A file generated by an external tool (above).
struct Origin {
    Symbol file;    // the generated file, normalized
    Symbol source;  // what it was generated from: "economy.xlsx"
    Symbol tool;    // what generated it: sheets-export; empty if not declared
};

// Where a load defined a name: a macro (`#define NAME`, `#define NAME (body)`, a top-level
// `[NAME ...]`), or a script function its #autorun commands define
// (tools::script_functions, <baker/tools/reference.hpp>). For a tool's completion,
// go-to-definition, and checks.
struct Definition {
    Symbol name;
    Symbol file;
    int32_t line = 0;
    bool flag = false;  // a macro with no body: #define NAME
};

// Who made a flag, for #ifdef: the host in code (LoadSession::define, ProjectOptions::defines),
// the project file's (defines ...), or a file's #define.
enum class DefineFrom : uint8_t { Host, Project, File };

// A flag that stands, and who made it: for check's and the reference's JSON, and explain.
struct ActiveDefine {
    Symbol name;
    DefineFrom from = DefineFrom::Host;
    Symbol file;  // a file's #define: where
    int32_t line = 0;
};

// A branch of an #ifdef or #ifndef that a read took: the lines of `file` it holds, and the
// name that chose it. explain names it for a value read there.
struct ConditionalSection {
    Symbol name;
    bool negated = false;      // #ifndef: taken because `name` was not defined
    bool else_branch = false;  // the #else: taken because the test was false
    Symbol file;
    int32_t begin = 0, end = 0;  // the directive's line and the closing #else or #endif's
};

// "host", "project" or "file", as the JSON documents write a define's origin.
[[nodiscard]] std::string_view define_from_name(DefineFrom from) noexcept;

// State shared by all files read through it. Macros and defines persist from one file to
// the next, as in the original; a fresh session starts empty. Copying a session copies
// its defines, macros, include directories, reader, and limits.
class LoadSession {
public:
    // Writes the whole file at `path` to `out` and returns true, or returns false if it
    // cannot read it.
    using Reader = Callback<bool(std::string_view path, TextSink out)>;

    LoadSession();
    // Its state (defines, packs, origins, ...) from `alloc`, which must outlive it: an
    // owner that keeps sessions (a Config) passes its own. A copy keeps its source's
    // allocator; the default constructor uses the default allocator.
    explicit LoadSession(const Allocator& alloc);
    LoadSession(const LoadSession& other);
    LoadSession(LoadSession&& other) noexcept;
    LoadSession& operator=(const LoadSession& other);
    LoadSession& operator=(LoadSession&& other) noexcept;
    ~LoadSession();

    // A flag, for #ifdef; `from` is who made it, the host's own code unless it says.
    void define(Symbol name, DefineFrom from = DefineFrom::Host);
    void define(Symbol name, Ref<Array> body);  // a macro; null body means a flag
    void undefine(Symbol name);
    [[nodiscard]] bool is_defined(Symbol name) const;
    [[nodiscard]] const Array* macro(Symbol name) const;  // null unless a macro

    // Replaces file access (default: the local filesystem), e.g. to serve files from
    // memory or a socket. A null reader restores the default.
    void set_reader(Reader reader);
    [[nodiscard]] const Reader& reader() const noexcept;

    // Lists a directory: calls `entry` with each entry's path (the directory joined with its
    // name; files and directories alike) and returns true, or returns false if it cannot
    // list `dir`. The Config lists a directory of layers with it (Config::push_layer_dir).
    using Lister =
        Callback<bool(std::string_view dir, Callback<void(std::string_view path)> entry)>;
    // Replaces directory listing (default: the local filesystem), as set_reader replaces
    // reading. A null lister restores the default.
    void set_lister(Lister lister);
    [[nodiscard]] const Lister& lister() const noexcept;

    // Searched, in order, after the including file's directory.
    void add_include_dir(std::string_view dir);
    void clear_include_dirs();
    // #autorun commands, in load order.
    [[nodiscard]] std::span<const Node> autorun() const noexcept;
    void clear_autorun();

    // The pack levels, hardest first: {"engine", "game", "task"}.
    void set_pack_levels(std::initializer_list<Symbol> levels);
    void set_pack_levels(std::span<const Symbol> levels);
    [[nodiscard]] std::span<const Pack> packs() const noexcept;
    [[nodiscard]] const Pack* pack_of(Symbol file) const noexcept;  // null: not a pack
    // The files that declared an origin, in the order they were read.
    [[nodiscard]] std::span<const Origin> origins() const noexcept;
    // Every macro definition the session's reads made, in the order read, each where it is
    // written: a name defined twice is listed twice, and one #undef'd stays listed
    // (is_defined says which stand). Macros a host defines in code are not listed.
    [[nodiscard]] std::span<const Definition> macro_definitions() const noexcept;
    // The flags that stand, in the order they were made, each with who made it: the host's,
    // the project's, and the files' #define, less those #undef'd. Macros are
    // macro_definitions().
    [[nodiscard]] std::span<const ActiveDefine> active_defines() const noexcept;
    // Every #ifdef or #ifndef branch the session's reads took, in the order read.
    [[nodiscard]] std::span<const ConditionalSection> conditional_sections() const noexcept;
    [[nodiscard]] const Origin* origin_of(Symbol file) const noexcept;  // null: none
    // Warnings from the files read, in order (the one-way rule), until cleared.
    [[nodiscard]] std::span<const Error> warnings() const noexcept;
    void clear_warnings();

    ParseLimits limits;
    // Set for an edit-mode parse: records source text and node spans (source_map.hpp).
    // Null (the default) is a gameplay parse, which keeps only the tree.
    SourceMap* source_map = nullptr;
    // Set before a load that will be cached (write_cache): each top-level read then records
    // the files it read and the defines it began with, so the cache can tell when it is
    // stale and replay the load's effects on a session.
    bool record_for_cache = false;
    // Enciphers the caches written with this session and deciphers those read (cache.hpp).
    const Cipher* cipher = nullptr;
    // Refuses every cache: reads through this session parse text, which no input can make
    // crash the reader. A cache is a memory image that a forged file can point anywhere, so a
    // loader of content from outside the game's own packages (mods, user files) sets this.
    bool text_only = false;
    // Refuses #include, #merge, and their kin, each with a located error: the text read may
    // reach no other file. With text_only, for text from outside the game, such as a layer
    // a live game receives (Config::push_layer_text).
    bool refuse_includes = false;
    // Where the trees read through this session come from: each read is one arena from
    // it, which must outlive the tree. Null: the default allocator.
    const Allocator* allocator = nullptr;

    struct State;  // defined in parse.cpp

private:
    friend class detail::Parser;
    friend struct detail::SessionAccess;
    friend Expected<Ref<Array>> read_string(std::string_view, std::string_view, LoadSession&);
    friend Expected<Ref<Array>> read_file(std::string_view, LoadSession&);

    // The public options above, from `o`: what every copy and move carries.
    void copy_options(const LoadSession& o) noexcept;

    State* st_;
};

[[nodiscard]] Expected<Ref<Array>> read_file(std::string_view path, LoadSession& session);
[[nodiscard]] Expected<Ref<Array>> read_file(std::string_view path);
// `name` is used as the file name in errors and as the base for relative includes.
[[nodiscard]] Expected<Ref<Array>> read_string(std::string_view text, std::string_view name,
                                               LoadSession& session);
[[nodiscard]] Expected<Ref<Array>> read_string(std::string_view text,
                                               std::string_view name = "<string>");

}  // namespace baker
